// Builds js/lang/<code>.js from i18n/<code>.json (flat "path": "text" pairs, the format used in the
// language team's review sheet). Checks every key against the English text in js/content.js.
// Usage: node tools/build-lang.js            (all languages in i18n/)
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const NAMES = { my: 'မြန်မာ (Burmese)', hi: 'हिन्दी (Hindi)', ta: 'தமிழ் (Tamil)' };
const FIXED = new Set(['type', 'icon', 'code', 'helpline']);

global.window = {};
require(path.join(root, 'js/content.js'));
const en = window.SCAM_TEXT.en;

// Flat map of every translatable English string.
const english = {};
(function walk(v, p) {
  if (typeof v === 'string') { english[p] = v; return; }
  if (Array.isArray(v)) return v.forEach((x, i) => walk(x, `${p}[${i}]`));
  for (const k in v) if (!(p === '' && k === 'manual') && !FIXED.has(k)) walk(v[k], p ? `${p}.${k}` : k);
})(en, '');

const tokens = (s) => (s.match(/\{\w+\}/g) || []).sort().join(',');
function setPath(obj, p, value) {
  const parts = p.match(/[^.[\]]+/g);
  let cur = obj;
  parts.forEach((part, i) => {
    const last = i === parts.length - 1, nextIsIndex = !last && /^\d+$/.test(parts[i + 1]);
    if (last) cur[part] = value;
    else cur = cur[part] = cur[part] || (nextIsIndex ? [] : {});
  });
}

let failed = false;
for (const file of fs.readdirSync(path.join(root, 'i18n')).filter((f) => f.endsWith('.json'))) {
  const code = path.basename(file, '.json');
  const flat = JSON.parse(fs.readFileSync(path.join(root, 'i18n', file), 'utf8'));
  const out = {}, problems = [];
  for (const [k, v] of Object.entries(flat)) {
    if (!(k in english)) { problems.push(`unknown or fixed key: ${k}`); continue; }
    if (typeof v !== 'string' || !v.trim()) { problems.push(`empty: ${k}`); continue; }
    if (tokens(v) !== tokens(english[k])) { problems.push(`placeholders differ in ${k}: "${tokens(english[k])}" vs "${tokens(v)}"`); continue; }
    setPath(out, k, v.trim());
  }
  const missing = Object.keys(english).filter((k) => !(k in flat));
  if (problems.length) { failed = true; console.log(`${code}: ${problems.length} problem(s)\n  ` + problems.join('\n  ')); }
  const js = `// ${NAMES[code] || code}: generated by tools/build-lang.js from i18n/${file}. Do not edit by hand.\n` +
    `// Text not listed here falls back to English (js/content.js).\n` +
    `window.SCAM_LANGS.push(${JSON.stringify({ code, name: NAMES[code] || code })});\n` +
    `window.SCAM_TEXT[${JSON.stringify(code)}] = ${JSON.stringify(out, null, 2)};\n`;
  fs.writeFileSync(path.join(root, 'js/lang', code + '.js'), js);
  console.log(`${code}: ${Object.keys(flat).length - problems.length} strings written, ${missing.length} left in English (${missing.slice(0, 8).join(', ')}${missing.length > 8 ? ', …' : ''})`);
}
process.exit(failed ? 1 : 0);
